// Начальный зум шахматки.
//
// Окно по умолчанию задаётся в Timeline.tsx: на компьютере ±7 дней вокруг
// сегодня, на планшете ±6. Сразу после монтирования библиотека умеет домножить
// это окно на коэффициент — им и пользуемся.
//
// ИСТОРИЯ (важно, ломалось дважды):
// Здесь стояло 3.5 для компьютера. Окно ±7 дней — это 14 дней, и 14 × 3.5 = 49:
// шахматка открывалась почти на два месяца, хотя дефолт чинили отдельно.
// Менеджерам нужен ближний горизонт — заезды-выезды этой и следующей недели,
// поэтому на компьютере окно не растягиваем вовсе.

export type TimelineScreen = {
    isPhone: boolean;
    isMobile: boolean;
};

/**
 * Во сколько раз домножить окно по умолчанию.
 * `null` — не трогать окно (и не дёргать библиотеку зря).
 */
export const getInitialZoomFactor = ({ isPhone, isMobile }: TimelineScreen): number | null => {
    // Телефон ведёт свой диапазон отдельно (mobileVisibleRange).
    if (isPhone) return null;
    // Планшет: экран узкий, поэтому окно ужимаем вдвое.
    if (isMobile) return 0.5;
    // Компьютер: ±7 дней — это уже нужное окно.
    return null;
};
