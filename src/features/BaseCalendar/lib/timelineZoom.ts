// Начальный зум шахматки.
//
// Окно по умолчанию задаётся в Timeline.tsx: на компьютере ±7 дней вокруг
// сегодня, на планшете ±6. Сразу после монтирования библиотека домножает это
// окно на коэффициент — им и задаём итоговый обзор.
//
// РЕШЕНИЕ ДАРЬИ (27.08.2026): на компьютере нужен ШИРОКИЙ обзор — коэффициент
// 3.5, то есть около 49 дней на экране. Коротко пробовали окно ровно ±7 дней
// (14 дней, столбцы втрое шире) — оказалось неудобно, дат помещается слишком
// мало. Не «оптимизировать» это значение снова без её просьбы.
//
// Отдельно от этого: жалоба из августа была про МАСШТАБ — шахматка
// открывалась помесячными столбцами вместо дневных. Это чинится не здесь,
// а начальной единицей масштаба в Timeline.tsx (`useState<ZoomUnit>('day')`).

export type TimelineScreen = {
    isPhone: boolean;
    isMobile: boolean;
};

/**
 * Во сколько раз домножить окно по умолчанию.
 * `null` — не трогать окно (и не дёргать библиотеку зря).
 */
export const getInitialZoomFactor = ({ isPhone, isMobile }: TimelineScreen): number | null => {
    // Телефон ведёт свой диапазон отдельно (mobileVisibleRange).
    if (isPhone) return null;
    // Планшет: экран узкий, поэтому окно ужимаем вдвое.
    if (isMobile) return 0.5;
    // Компьютер: широкий обзор, ~49 дней.
    return 3.5;
};
